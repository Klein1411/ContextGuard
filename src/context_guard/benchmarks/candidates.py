from __future__ import annotations

import json
from pathlib import Path
from typing import TypedDict

from context_guard import ContextGuard, GuardConfig
from context_guard.adapters.base import CompressorAdapter
from context_guard.benchmarks.dataset import DatasetRecord


class CandidateRecord(TypedDict):
    id: str
    language: str
    domain: str
    original: str
    candidate: str
    source_adapter: str
    label_status: str
    protected_fact_count: int
    notes: str


def build_unverified_candidates(
    records: list[DatasetRecord], compressor: CompressorAdapter
) -> list[CandidateRecord]:
    """Generate Tier C candidates without assigning a correctness label."""
    candidates: list[CandidateRecord] = []
    for record in records:
        analysis = ContextGuard(
            GuardConfig(language=record["language"], profile=record["domain"])
        ).analyze(record["original"])
        candidate = compressor.compress(record["original"], analysis.protected_spans)
        candidates.append(
            {
                "id": f"{compressor.name}-{record['id']}",
                "language": record["language"],
                "domain": record["domain"],
                "original": record["original"],
                "candidate": candidate,
                "source_adapter": compressor.name,
                "label_status": "unverified",
                "protected_fact_count": len(analysis.protected_spans),
                "notes": (
                    "Candidate generated by an adapter; correctness is unverified and "
                    "requires manual audit before metric claims."
                ),
            }
        )
    return candidates


def write_candidates(records: list[CandidateRecord], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False, sort_keys=True) + "\n")


def load_candidates(path: Path) -> list[CandidateRecord]:
    with path.open(encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def validate_candidates(records: list[CandidateRecord]) -> dict[str, object]:
    required = {
        "id",
        "language",
        "domain",
        "original",
        "candidate",
        "source_adapter",
        "label_status",
        "protected_fact_count",
        "notes",
    }
    if any(set(record) != required for record in records):
        raise ValueError("candidate dataset schema fields do not match the Tier C contract")
    if len({record["id"] for record in records}) != len(records):
        raise ValueError("candidate dataset contains duplicate ids")
    if any(record["label_status"] != "unverified" for record in records):
        raise ValueError("Tier C candidates must remain unverified until manual audit")
    return {
        "sample_count": len(records),
        "source_adapters": sorted({record["source_adapter"] for record in records}),
        "label_statuses": sorted({record["label_status"] for record in records}),
    }
