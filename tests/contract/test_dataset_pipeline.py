def test_m11_records_are_balanced_and_hidden_labels_are_separate(tmp_path: Path) -> None:
    data_home = tmp_path / "data"
    raw_technical = data_home / "raw" / "technical"
    raw_technical.mkdir(parents=True)
    fastapi_text = (
        "# FastAPI\n\n"
        + "Technical paragraph with enough content for the controlled benchmark. " * 8
    )
    (raw_technical / "fastapi-README.md").write_text(
        fastapi_text,
        encoding="utf-8",
    )
    (raw_technical / "contextguard-README.md").write_text(
        "# ContextGuard\n\n" + "Safety validation paragraph with enough content. " * 8,
        encoding="utf-8",
    )
    # The source pools are external in production; this test exercises the exact
    # stratification contract using the same builder after source files are staged.
    import scripts.dataset_pipeline as pipeline

    original = pipeline._load_pools
    pipeline._load_pools = lambda _data_home: {
        domain: [
            {
                "language": "en",
                "original": f"{domain} source context",
                "candidate": f"{domain} candidate",
                "source_name": "test",
                "source_id": str(index),
                "source_type": "natural",
                "provenance": "test",
            }
            for index in range(25)
        ]
        for domain in ("general", "academic", "business", "technical")
    }
    try:
        dev, hidden = build_records(data_home)
    finally:
        pipeline._load_pools = original
    assert len(dev) == 280
    assert len(hidden) == 120
    assert all("label" in row for row in dev)
    assert all("label" not in row for row in hidden)
    assert len({(row["domain"], row["language"], row["label"]) for row in dev}) == 16
    manifest = build_manifest(data_home, dev, hidden)
    assert manifest["counts"] == {"total": 400, "dev": 280, "hidden": 120, "per_cell": 25}
    labels_path = data_home / "benchmark_cache" / "natural_adversarial_v1_hidden_labels.jsonl"
    assert sum(1 for _ in labels_path.open(encoding="utf-8")) == 120


def test_download_resumable_uses_part_path(tmp_path: Path, monkeypatch) -> None:
    source = tmp_path / "source.bin"
    target = tmp_path / "target.bin"
    source.write_bytes(b"contextguard-payload")

    class Response:
        status = 200

        def __enter__(self):
            return self

        def __exit__(self, *_args):
            return False

        def read(self, _size):
            payload = source.read_bytes()
            source.write_bytes(b"")
            return payload

    monkeypatch.setattr("urllib.request.urlopen", lambda *_args, **_kwargs: Response())
    digest = download_resumable("https://example.invalid/file", target)
    assert target.read_bytes() == b"contextguard-payload"
    assert len(digest) == 64
    assert not target.with_suffix(target.suffix + ".part").exists()


def test_public_manifest_contains_no_local_path(tmp_path: Path) -> None:
    # Keep this assertion small and explicit: local raw paths must not leak into
    # the committed public manifest generated by the pipeline.
    manifest_path = Path("artifacts/final/natural_adversarial_v1_manifest.json")
    if manifest_path.exists():
        payload = json.loads(manifest_path.read_text(encoding="utf-8"))
        assert all("local_paths" not in source for source in payload.get("sources", []))
